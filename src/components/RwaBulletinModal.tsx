import React, { useState } from 'react';
import { CitySmogContext, ImpactSimulationResults, HouseholdProfile } from '../types';
import { X, Copy, Check, MessageSquare, Share2 } from 'lucide-react';

interface RwaBulletinModalProps {
  isOpen: boolean;
  onClose: () => void;
  city: CitySmogContext;
  impact: ImpactSimulationResults;
  profile: HouseholdProfile;
}

export const RwaBulletinModal: React.FC<RwaBulletinModalProps> = ({
  isOpen,
  onClose,
  city,
  impact,
  profile,
}) => {
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  const todayStr = new Date().toLocaleDateString('en-IN', {
    weekday: 'short',
    day: 'numeric',
    month: 'short',
    year: 'numeric',
  });

  const bulletinText = `🚨 *URGENT RWA / APARTMENT SMOG ADVISORY* 🚨
📍 *Station:* ${city.name} | *Date:* ${todayStr}
📊 *Current AQI:* ${city.currentAQI} (${city.aqiCategory.toUpperCase()})
🌫️ *PM2.5 Level:* ${city.pm25} µg/m³ (${(city.pm25 / 15).toFixed(1)}x WHO Safe Limit)

⚠️ *ATMOSPHERIC INVERSION WARNING:*
Cold ground surface air is trapping toxic particulate matter. Peak inversion trapping occurs between *${city.highRiskInversionHours}*.

🪟 *CRITICAL VENTILATION PROTOCOL:*
• *SEAL WINDOWS & DOORS:* Keep balcony doors tightly sealed during morning (05:00-09:30 AM) and night (08:00 PM-02:00 AM).
• *SAFE VENTILATION WINDOW:* If needed, open cross-ventilation ONLY between *${city.safeVentilationWindows}* when solar heating disperses the ground trap.

👥 *MANDATORY SOCIETY-WIDE COMMUNITY ACTIONS:*
1. 🚫 *ZERO OPEN BURNING:* Security guards & gardeners must NOT burn dried leaves or waste. RWA has mandated electric heaters at guard posts.
2. 🚗 *SCHOOL BUS & COMMUTE SHIFT:* Please switch off idling car engines in parking basements. Form carpools or take the metro for transit.
3. 🏃‍♂️ *PROTECT SENIORS & CHILDREN:* Cancel morning outdoor sports and balcony walks until after 11:30 AM.

🌱 *COLLECTIVE IMPACT:*
If ${impact.communityFamiliesCount} families follow this protocol, our society avoids *${impact.communityMonthlyCo2SavedKg} kg CO₂* and prevents *${impact.communityMonthlyPmPreventedKg} kg of toxic particulate matter* this month!

— Generated by *VayuSaathi* (Household Air & Exposure Co-Pilot)`;

  const handleCopy = () => {
    navigator.clipboard.writeText(bulletinText);
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/50 p-4 backdrop-blur-xs">
      <div className="relative w-full max-w-2xl rounded-lg border border-stone-300 bg-white p-6 shadow-xl max-h-[90vh] flex flex-col">
        {/* Header */}
        <div className="flex items-center justify-between border-b border-stone-200 pb-4">
          <div className="flex items-center gap-2">
            <MessageSquare className="h-5 w-5 text-sage-600" />
            <div>
              <h3 className="text-base font-bold text-ink">
                RWA / Society WhatsApp Smog Bulletin
              </h3>
              <p className="text-xs text-ink-muted">
                Pre-formatted for your apartment society or neighborhood WhatsApp group.
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="rounded p-1 text-stone-400 hover:text-ink hover:bg-stone-100"
          >
            <X className="h-5 w-5" />
          </button>
        </div>

        {/* Content Box */}
        <div className="mt-4 flex-1 overflow-y-auto rounded border border-stone-200 bg-stone-50 p-4 font-mono text-xs leading-relaxed text-ink whitespace-pre-wrap select-all">
          {bulletinText}
        </div>

        {/* Footer Actions */}
        <div className="mt-4 flex items-center justify-between border-t border-stone-200 pt-4">
          <span className="text-xs text-ink-muted">
            Formatted with WhatsApp bolding (*text*) and clear emojis.
          </span>
          <div className="flex items-center gap-2">
            <button
              onClick={onClose}
              className="rounded border border-stone-300 bg-white px-3 py-1.5 text-xs font-semibold text-ink hover:bg-stone-100"
            >
              Close
            </button>
            <button
              onClick={handleCopy}
              className="flex items-center gap-1.5 rounded border border-sage-600 bg-sage-600 px-4 py-1.5 text-xs font-semibold text-white hover:bg-sage-700 transition-colors shadow-xs"
            >
              {copied ? (
                <>
                  <Check className="h-4 w-4" />
                  <span>Copied to Clipboard!</span>
                </>
              ) : (
                <>
                  <Copy className="h-4 w-4" />
                  <span>Copy WhatsApp Text</span>
                </>
              )}
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
